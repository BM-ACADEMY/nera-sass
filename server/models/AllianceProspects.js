const { defineModel, Mixed } = require('../db/mongo');

module.exports = defineModel('alliance_prospects', {
  id: { type: Number },
  campaign_id: { type: Number },
  audience: { type: String },
  name: { type: String },
  business_name: { type: String },
  phone: { type: String },
  email: { type: String },
  industry: { type: String },
  location: { type: String },
  channel_pref: { type: String },
  channel: { type: String },
  consent: { type: Boolean, default: false },
  consent_source: { type: String },
  consent_at: { type: Date },
  source: { type: String, default: "file_upload" },
  status: { type: String, default: "new" },
  ai_score: { type: Number },
  suppressed: { type: Boolean, default: false },
  current_touch: { type: Number, default: 0 },
  created_at: { type: Date, default: Date.now },
  updated_at: { type: Date, default: Date.now },
  custom_fields: { type: Mixed, default: () => ({}) },
  tags: { type: [String], default: () => [] },
  consent_evidence: { type: String },
  consent_scope: { type: String },
  tenant_id: { type: Number },
}, { autoId: true, unique: [['phone']], uniqueCaseInsensitive: [['email']], indexes: [['campaign_id'], ['tenant_id']] });
