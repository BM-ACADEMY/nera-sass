const { defineModel, Mixed } = require('../db/mongo');

module.exports = defineModel('alliance_whatsapp_campaigns', {
  id: { type: Number },
  name: { type: String },
  audience: { type: String },
  template_id: { type: Number },
  template_name: { type: String },
  template_language: { type: String, default: "en" },
  template_body: { type: String },
  parameter_mapping: { type: Mixed, default: () => [] },
  phone_number_id: { type: String },
  status: { type: String, default: "scheduled" },
  scheduled_at: { type: Date, default: Date.now },
  started_at: { type: Date },
  completed_at: { type: Date },
  created_by: { type: Number },
  created_at: { type: Date, default: Date.now },
  updated_at: { type: Date, default: Date.now },
  followup_template_id: { type: Number },
  followup_template_name: { type: String },
  followup_template_language: { type: String },
  followup_template_body: { type: String },
  followup_parameter_mapping: { type: Mixed, default: () => [] },
  followup_delay_days: { type: Number, default: 4 },
  followup_repeat_days: { type: Number, default: 4 },
  max_followups: { type: Number, default: 1 },
  followup_delay_minutes: { type: Number, default: 5760 },
}, { autoId: true, indexes: [['template_id'], ['followup_template_id']] });
